/**
 * Translates a string added by Tasks Board
 *
 * @param {string} text The English source text
 * @param {object} vars Placeholders like {count}
 * @return {string} The translated text
 */
export function tbt(text, vars = {}) {
	const language = getLanguage()
	const table = translations[language] || translations[language.split(/[-_]/)[0]] || {}
	const translated = table[text] || text
	return translated.replace(/{([a-zA-Z0-9_]+)}/g, (match, key) => (key in vars ? String(vars[key]) : match))
}
